//! Compiles every GLSL shader of the workspace `shaders/` folder (`*.vert`, `*.frag`, `*.comp`) to
//! SPIR-V with glslc, with `shaders/include` and the generated `params.glsl` on the include path, and embeds the
//! executable icon and version resource (`appres`).

use std::{env, path::PathBuf, process::Command};

/// Shader file extensions compiled by `build.rs`, one SPIR-V file `<name>.spv` each in `OUT_DIR`.
const SHADER_EXTENSIONS: [&str; 3] = ["vert", "frag", "comp"];

fn glslc() -> PathBuf {
    if let Ok(sdk) = env::var("VULKAN_SDK") {
        let p = PathBuf::from(sdk).join("Bin").join("glslc.exe");
        if p.exists() {
            return p;
        }
    }
    PathBuf::from("glslc")
}

/// The short hash of the commit being built (`PHOXIUM_COMMIT` for the About section), or `unknown` without git or
/// outside a checkout. No date or time is embedded: the same commit builds the same binary. `PHOXIUM_COMMIT` set in
/// the environment wins (a packaging script, a build from a source archive).
fn embed_commit() {
    println!("cargo:rerun-if-env-changed=PHOXIUM_COMMIT");
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let git = |args: &[&str]| -> Option<String> {
        let out = Command::new("git").arg("-C").arg(&manifest).args(args).output().ok()?;
        let s = String::from_utf8(out.stdout).ok()?.trim().to_string();
        (out.status.success() && !s.is_empty()).then_some(s)
    };
    let commit = env::var("PHOXIUM_COMMIT")
        .ok()
        .filter(|c| !c.trim().is_empty() && c.chars().all(|ch| ch.is_ascii_alphanumeric()))
        .or_else(|| git(&["rev-parse", "--short", "HEAD"]).filter(|c| c.chars().all(|ch| ch.is_ascii_hexdigit())))
        .unwrap_or_else(|| "unknown".to_string());
    println!("cargo:rustc-env=PHOXIUM_COMMIT={commit}");
    // Rebuilt when HEAD moves: the HEAD file (a branch switch) and the file of the branch it names (a commit).
    for path in [
        git(&["rev-parse", "--git-path", "HEAD"]),
        git(&["symbolic-ref", "-q", "HEAD"]).and_then(|r| git(&["rev-parse", "--git-path", &r])),
    ]
    .into_iter()
    .flatten()
    {
        let p = PathBuf::from(&path);
        let p = if p.is_absolute() { p } else { manifest.join(p) };
        if p.exists() {
            println!("cargo:rerun-if-changed={}", p.display());
        }
    }
}

fn main() {
    println!("cargo:rerun-if-env-changed=VULKAN_SDK");
    embed_commit();
    // Executable icon and VERSIONINFO (assets/icon, regenerated by `cargo run -p appres --example gen_icon`).
    appres::embed_for_build_script(
        &PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("../../assets/icon/icon.ico"),
        "phoxium",
        "Phoxium, physically based CRT shader",
    );
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap())
        .join("..")
        .join("..")
        .join("shaders");
    // params.glsl must exist before the shaders that include it are compiled.
    generate_params(&out);
    // A directory is scanned recursively for changes (shaders/include too).
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut sources: Vec<PathBuf> = std::fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", dir.display()))
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| {
            p.is_file()
                && p.extension()
                    .and_then(|x| x.to_str())
                    .is_some_and(|x| SHADER_EXTENSIONS.contains(&x))
        })
        .collect();
    sources.sort();
    for src in sources {
        let name = src.file_name().unwrap().to_string_lossy().into_owned();
        let dst = out.join(format!("{name}.spv"));
        let status = Command::new(glslc())
            .args(["-O", "--target-env=vulkan1.3", "-I"])
            .arg(dir.join("include"))
            .arg("-I")
            .arg(&out)
            .arg("-o")
            .arg(&dst)
            .arg(&src)
            .status()
            .unwrap_or_else(|e| panic!("cannot run glslc ({e}); install the Vulkan SDK and set VULKAN_SDK"));
        assert!(status.success(), "glslc failed on {}", src.display());
    }
}

/// Generates `params.rs` and `params.glsl` in `OUT_DIR` from the parameter table `params/*.toml` (paramgen),
/// then compiles a shader that includes `params.glsl` with glslc. Test-only files (`params/_*.toml`) are
/// included in non-release builds only, which also set `cfg(phoxium_test_params)`.
fn generate_params(out: &std::path::Path) {
    let dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap())
        .join("..")
        .join("..")
        .join("params");
    println!("cargo:rerun-if-changed={}", dir.display());
    println!("cargo::rustc-check-cfg=cfg(phoxium_test_params)");
    let include_test = env::var("PROFILE").map_or(true, |p| p != "release");
    if include_test {
        println!("cargo:rustc-cfg=phoxium_test_params");
    }
    let table = match paramgen::load_dir(&dir, include_test) {
        Ok(t) => t,
        Err(e) => {
            eprintln!("error: parameter table: {e}");
            std::process::exit(1);
        }
    };
    std::fs::write(out.join("params.rs"), paramgen::rust_source(&table)).unwrap();
    std::fs::write(out.join("params.glsl"), paramgen::glsl_source(&table)).unwrap();
    let check = out.join("params_check.comp");
    std::fs::write(
        &check,
        "#version 450\n#extension GL_GOOGLE_include_directive : require\n#include \"params.glsl\"\n\
         layout(local_size_x = 1) in;\nvoid main() {}\n",
    )
    .unwrap();
    let status = Command::new(glslc())
        .args(["--target-env=vulkan1.3", "-o"])
        .arg(out.join("params_check.spv"))
        .arg(&check)
        .status()
        .unwrap_or_else(|e| panic!("cannot run glslc ({e}); install the Vulkan SDK and set VULKAN_SDK"));
    assert!(status.success(), "glslc failed on the generated params.glsl");
}
